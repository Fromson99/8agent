"""제안자 — 불릿 `■` `·` `▶` (SPEC §6.1).

## 번호가 없는 문서에도 마커는 있다

실측(ss2207 별지1·별지2)에서 이 문서는 조·항 번호가 닿지 않는 구역을 불릿으로 가른다:

    · 세부 운용지시          · 기타 특약사항
    ■ 신탁기간 변경          ■ 운용지시 변경        ■ 기타 변경내용
    ▶ 기타 특약 투자자 확인 사항

번호가 없을 뿐 **계열이다.** 이것이 후보로 서지 않으면 그 페이지는 마커가 하나도 없는
문서가 되고, 적합도가 바닥으로 떨어져 통째로 cold 라우팅된다.

## 서수가 없다는 것의 의미

불릿은 `①②③` 과 달리 **자기가 몇 번째인지 말하지 않는다.** 그래서

    · `ordinal=None` 이다. 서수 게이트는 이 후보를 건너뛴다(`global_inner/ordinal.py`).
      `annex.py` 의 `부칙` 이 같은 처지다.
    · 계열 정합(S2)이 "번호가 한 칸씩 전진하는가" 로 구조/인용을 가를 수 없다. 대신
      가드(블록 여는 자리 · 조사 · 완전형)와 **들여쓰기**(`global_outer/indent.py`)가
      가른다 — 들여쓰기는 서수를 보지 않으므로 이 계열에서도 그대로 작동한다.

## 글리프마다 다른 family 인 이유

`■` 와 `·` 는 같은 문서에서 **다른 깊이**로 쓰인다(별지2: `■ 운용지시 변경` 아래에
표, 별지1: `· 세부 운용지시` 아래에 표). 하나의 family 로 묶으면 사다리가 둘을 같은
칸에 얹어 버린다. `annex.py` 가 `별지`/`별표`/`서식` 을 가르는 것과 같은 이유다.
어느 글리프가 더 얕은지는 **여기서 정하지 않는다** — 문서가 유도한다(§6).

## 체크박스는 불릿이 아니다

같은 문서에 `[ ] 3. 수익증권`, `□ 우편` 이 잔뜩 나온다. 이건 **선택지**이지 구역을
여는 마커가 아니다. `□` `☐` `[ ]` 를 넣으면 별지1 한 쪽에서만 24개의 가짜 후보가
서고 사다리가 무너진다. 넣지 않는다.
"""

from __future__ import annotations

import re

from core.structure.model import Block, Candidate
from core.structure.proposers import scan

ID = "bullet"
ROLE = "proposer"
LANG = "any"
FAMILY = "bullet"
SURFACE = "■ · ▶ 등 서수 없는 불릿"

# 실측에서 구역을 여는 데 쓰인 글리프만. 체크박스(□ ☐ [ ])는 위 주석대로 제외하고,
# `※` 도 뺀다 — 같은 문서에서 주석을 여는 데 쓰인다(`※ 수령처 우편인 경우라도 …`).
# `·` 는 가운뎃점(U+00B7)·불릿(U+2022)·한글 가운뎃점(U+318D)이 섞여 들어온다.
_GLYPHS = "■◼▪●◆◇▶▷➤·•ㆍ‧"

# 같은 모양으로 취급할 글리프 — 대표형으로 접는다. `■` 와 `◼` 를 다른 층으로 두면
# 판본이 글꼴만 바꿔도 사다리가 달라진다.
_CANON = {
    "◼": "■", "▪": "■",
    "◇": "◆",
    "▷": "▶", "➤": "▶",
    "•": "·", "ㆍ": "·", "‧": "·",
}

# 블록 첫머리의 불릿만 완전형으로 본다. 문장 중간의 `·` 는 대개 낱말 구분자다
# (`우편·이메일`). 뒤에 공백이 있어야 마커다 — 붙어 있으면 구분자로 본다.
_FULL = re.compile(rf"^\s*([{_GLYPHS}])\s+(?=\S)")
# 줄 중간에 오는 것도 후보로는 세운다 — 가드가 가르게 두는 것이 §4 S0 의 원칙이다.
# 다만 앞뒤가 모두 한글이면(`우편·이메일`) 낱말 구분자이므로 제외한다.
_FRAGMENT = re.compile(rf"(?<![가-힣A-Za-z0-9])([{_GLYPHS}])\s+(?=\S)")


def _ordinal(m: re.Match):
    """불릿은 자기가 몇 번째인지 말하지 않는다 — 서수 없음."""
    return None


def propose(block: Block, lex) -> list[Candidate]:
    # 글리프마다 다른 계열 (위 주석) — 두 패턴 모두 group(1) 이 글리프다.
    return scan(block, FAMILY, _FULL, _ordinal, fragment=_FRAGMENT,
                family_of=lambda m: f"bullet_{_CANON.get(m.group(1), m.group(1))}")
