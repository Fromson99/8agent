"""Deterministic identifiers and hashes for ``legal-graph-v1``.

The helpers deliberately accept only JSON-like values.  Falling back to
``repr`` or ``str`` would make identifiers depend on process-local object
representations and would hide schema mistakes in the generator.
"""

from __future__ import annotations

import hashlib
import json
import math
import re
from dataclasses import is_dataclass
from enum import Enum
from typing import Any, Mapping


_ID_PREFIX = re.compile(r"^[a-z][a-z0-9_-]{0,47}$")
_STABLE_ID = re.compile(r"^[a-z][a-z0-9_-]{0,47}:[0-9a-f]{16,64}$")


class CanonicalJSONError(ValueError):
    """Raised when a value cannot be represented canonically as JSON."""


def _jsonable(value: Any) -> Any:
    if value is None or isinstance(value, (str, bool, int)):
        return value
    if isinstance(value, float):
        if not math.isfinite(value):
            raise CanonicalJSONError("NaN and infinity are not canonical JSON")
        return value
    if isinstance(value, Enum):
        return _jsonable(value.value)
    if hasattr(value, "to_dict") and callable(value.to_dict):
        return _jsonable(value.to_dict())
    if is_dataclass(value):
        raise CanonicalJSONError(
            f"dataclass {type(value).__name__} must define to_dict()"
        )
    if isinstance(value, Mapping):
        out: dict[str, Any] = {}
        for key, item in value.items():
            if not isinstance(key, str):
                raise CanonicalJSONError("canonical JSON object keys must be strings")
            out[key] = _jsonable(item)
        return out
    if isinstance(value, (list, tuple)):
        return [_jsonable(item) for item in value]
    raise CanonicalJSONError(f"unsupported canonical JSON value: {type(value).__name__}")


def canonical_json_text(value: Any) -> str:
    """Return the one compact UTF-8 JSON representation used for hashing."""
    try:
        return json.dumps(
            _jsonable(value),
            ensure_ascii=False,
            sort_keys=True,
            separators=(",", ":"),
            allow_nan=False,
        )
    except (TypeError, ValueError) as exc:
        if isinstance(exc, CanonicalJSONError):
            raise
        raise CanonicalJSONError(str(exc)) from exc


def canonical_json_bytes(value: Any) -> bytes:
    return canonical_json_text(value).encode("utf-8")


def sha256_hex(value: bytes | bytearray | memoryview | str) -> str:
    """Hash bytes, or the UTF-8 bytes of a string, with SHA-256."""
    if isinstance(value, str):
        payload = value.encode("utf-8")
    elif isinstance(value, (bytes, bytearray, memoryview)):
        payload = bytes(value)
    else:
        raise TypeError("sha256_hex accepts bytes-like values or str")
    return hashlib.sha256(payload).hexdigest()


def content_sha256(value: Any) -> str:
    """Hash a JSON-like value after canonical serialization."""
    return sha256_hex(canonical_json_bytes(value))


def stable_id(prefix: str, *parts: Any, length: int = 24) -> str:
    """Build a stable, namespaced identifier from semantic identity parts."""
    if not isinstance(prefix, str) or not _ID_PREFIX.fullmatch(prefix):
        raise ValueError(f"invalid stable-id prefix: {prefix!r}")
    if not 16 <= length <= 64:
        raise ValueError("stable-id digest length must be between 16 and 64")
    return f"{prefix}:{content_sha256(list(parts))[:length]}"


def validate_id(value: str, *, prefix: str | None = None) -> str:
    """Validate and return a stable id generated by :func:`stable_id`."""
    if not isinstance(value, str) or not _STABLE_ID.fullmatch(value):
        raise ValueError(f"invalid stable id: {value!r}")
    if prefix is not None and not value.startswith(f"{prefix}:"):
        raise ValueError(f"stable id {value!r} does not use prefix {prefix!r}")
    return value


# Short aliases used by streaming writers.
canonical_json = canonical_json_text
canonical_sha256 = content_sha256
