"""정의 표기 정규식의 정본 — 컴파일 국면(terms)과 검색 런타임(rag)이 함께 쓴다.

용어층 격리 규칙(tests/architecture/test_terms_isolation.py)은 검색 런타임이
lawrag/core/terms 를 **어디서도** import 하지 못하게 한다 — 두 국면은 코드가
아니라 파일(terms.json·npz)로만 만난다. 그런데 "「X」(이하 "Y"라 한다)" 같은
**정의 표기 문법** 자체는 국면의 상태가 아니라 한국 법령의 관례라, 양쪽이 같은
패턴을 봐야 한다(runtime 이 제 사본을 들고 있으면 두 정본이 갈라진다 — 실측
2026-08-19: rag/definitions.py 가 transcribe 를 끌어와 격리 위반). 그래서
패턴만 이 중립 지대에 둔다. 여기는 re 밖에 모른다 — 로더·저장·모델 금지.
"""
from __future__ import annotations

import re

_Q_OPEN = "\"“‘'"
_Q_CLOSE = "\"”’'"

# "금융투자업"이란 / "전문투자자"라 함은 — 따옴표가 용어 경계를 준다.
RE_QUOTED = re.compile(
    rf'[{_Q_OPEN}]([^{_Q_OPEN}{_Q_CLOSE}\n]{{1,40}})[{_Q_CLOSE}]\s*'
    r'(?:이란|란|이라\s*함은|라\s*함은)')

# 따옴표 없는 정의문 — `X이란 …를 말한다`. '이란'과 '함은'만 받는다:
# 모음 뒤의 맨 '란'(`펀드란`)까지 받으면 '계란' 류가 갈라져 들어온다.
# 정밀도가 우선이다 — Tier 1 은 신뢰도 최고 층이어야 한다.
RE_BARE = re.compile(
    r'(?:^|[\n.。]\s*|[①-⑳㉮-㉻]\s*|\d+\.\s*|[가-하]\.\s*)'
    r'([가-힣A-Za-z0-9·]{2,25}(?:\s[가-힣A-Za-z0-9·]{1,15}){0,3})'
    r'(?:이란|이라\s*함은|라\s*함은)\s[^.]{0,150}?말한다')

# 본용어(이하 "별칭"이라 한다) — 법령 제목은 「」 로 싸인다.
RE_YIHA = re.compile(
    rf'(?:「([^」]{{2,40}})」|([가-힣A-Za-z0-9·]+(?:\s?[가-힣A-Za-z0-9·]+){{0,5}}))\s*'
    rf'\(\s*이하\s*[{_Q_OPEN}]?([^){_Q_OPEN}{_Q_CLOSE}]{{2,25}}?)[{_Q_CLOSE}]?\s*'
    r'(?:이?라\s*(?:한다|합니다|함))\s*\)')

# "이 예금"·"해당 계좌" 류 지시 표현은 별칭이 아니라 문맥 대명사다.
_DEICTIC = ("이 ", "그 ", "해당 ", "동 ", "위 ", "본 ")
