CREATE TABLE SIDDA.LGL_PIPE_RESULT_A (
  JOB_ID VARCHAR2(32 BYTE) NOT NULL,
  SEQ_NO NUMBER(12) NOT NULL,
  BIND_HASH VARCHAR2(64 BYTE) NOT NULL,
  DATA_HASH VARCHAR2(64 BYTE) NOT NULL,
  BYTE_CNT NUMBER(14) NOT NULL,
  PART_CNT NUMBER(12) NOT NULL,
  BODY_B64 CLOB,
  PRIMARY KEY (JOB_ID, SEQ_NO),
  CHECK (BYTE_CNT > 0 AND ((SEQ_NO = 0 AND PART_CNT > 0) OR (SEQ_NO > 0 AND PART_CNT = 0)))
);
