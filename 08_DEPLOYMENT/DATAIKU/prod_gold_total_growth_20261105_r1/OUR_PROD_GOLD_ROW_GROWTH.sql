-- 운영계 Dataiku: 현재 우리 34조각 Gold 적재에 사용하는 Oracle 연결에서 실행합니다.
-- 대상은 아래 명시한 SIDDG.IDD_B003_LGL_* 우리 13개 테이블만입니다.
-- 다른 업무의 골드 테이블, 개발계 SIDDS, 구형/시험 테이블은 포함하지 않습니다.
-- SRCH_ROW를 포함한 우리 13개 표의 실제 COUNT(*)를 합산합니다.
--
-- 첫 조회: 아래 CAST(NULL AS NUMBER)를 그대로 두고 전체 SELECT를 실행합니다.
-- 첫 조회가 끝난 뒤 TOTAL_GOLD_ROWS 숫자를 기록합니다.
-- 2~5분 뒤: NULL을 직전 TOTAL_GOLD_ROWS 숫자(쉼표 없이)로 바꾸고 다시 실행합니다.
-- 예: 직전 값이 1,000,000이면 CAST(1000000 AS NUMBER)로 바꿉니다.
-- ADDED_ROWS > 0 / GROWTH_STATUS = INCREASED이면 그 사이 우리 Gold 전체 행 수가 증가했습니다.
-- 같은 연결/대상에서 비교합니다. 동일 값 한 번만으로 작업 정지를 단정하지 않습니다.
-- 합계는 모든 저장 판본과 원문/검색/게시/벡터를 포함한 행 수이며 고유 문서 수가 아닙니다.
-- 이 SQL은 조회만 하며 데이터/상태/통계/설정을 변경하지 않습니다.
WITH P AS (
    SELECT CAST(NULL AS NUMBER) AS PREVIOUS_TOTAL_ROWS
    FROM DUAL
), COUNTS AS (
    SELECT 'IDD_B003_LGL_DOC_VER' AS TABLE_NAME, COUNT(*) AS ROW_COUNT
    FROM SIDDG.IDD_B003_LGL_DOC_VER
    UNION ALL
    SELECT 'IDD_B003_LGL_DOC_UNIT', COUNT(*)
    FROM SIDDG.IDD_B003_LGL_DOC_UNIT
    UNION ALL
    SELECT 'IDD_B003_LGL_DOC_BLK', COUNT(*)
    FROM SIDDG.IDD_B003_LGL_DOC_BLK
    UNION ALL
    SELECT 'IDD_B003_LGL_SRC_POST', COUNT(*)
    FROM SIDDG.IDD_B003_LGL_SRC_POST
    UNION ALL
    SELECT 'IDD_B003_LGL_SRCH_POST', COUNT(*)
    FROM SIDDG.IDD_B003_LGL_SRCH_POST
    UNION ALL
    SELECT 'IDD_B003_LGL_SRCH_ROW', COUNT(*)
    FROM SIDDG.IDD_B003_LGL_SRCH_ROW
    UNION ALL
    SELECT 'IDD_B003_LGL_SRCH_CHNL', COUNT(*)
    FROM SIDDG.IDD_B003_LGL_SRCH_CHNL
    UNION ALL
    SELECT 'IDD_B003_LGL_ONTL_POST', COUNT(*)
    FROM SIDDG.IDD_B003_LGL_ONTL_POST
    UNION ALL
    SELECT 'IDD_B003_LGL_ONTL_HEAD', COUNT(*)
    FROM SIDDG.IDD_B003_LGL_ONTL_HEAD
    UNION ALL
    SELECT 'IDD_B003_LGL_ONTL_ANC', COUNT(*)
    FROM SIDDG.IDD_B003_LGL_ONTL_ANC
    UNION ALL
    SELECT 'IDD_B003_LGL_VCTR_POST', COUNT(*)
    FROM SIDDG.IDD_B003_LGL_VCTR_POST
    UNION ALL
    SELECT 'IDD_B003_LGL_VCTR_ITEM', COUNT(*)
    FROM SIDDG.IDD_B003_LGL_VCTR_ITEM
    UNION ALL
    SELECT 'IDD_B003_LGL_VCTR_HEAD', COUNT(*)
    FROM SIDDG.IDD_B003_LGL_VCTR_HEAD
), TOTALS AS (
    SELECT COUNT(*) AS TABLE_COUNT,
           SUM(ROW_COUNT) AS TOTAL_GOLD_ROWS,
           MAX(CASE WHEN TABLE_NAME = 'IDD_B003_LGL_SRCH_ROW'
                    THEN ROW_COUNT END) AS SRCH_ROW_COUNT
    FROM COUNTS
)
SELECT SYSTIMESTAMP AS CHECKED_AT,
       SYS_CONTEXT('USERENV', 'DB_UNIQUE_NAME') AS DB_NAME,
       SYS_CONTEXT('USERENV', 'SERVICE_NAME') AS SERVICE_NAME,
       'SIDDG.IDD_B003_LGL_*' AS TARGET_SCOPE,
       T.TABLE_COUNT,
       T.TOTAL_GOLD_ROWS,
       TO_CHAR(T.TOTAL_GOLD_ROWS, 'FM999,999,999,999,999,999,990') AS TOTAL_ROWS_COMMA,
       T.SRCH_ROW_COUNT,
       P.PREVIOUS_TOTAL_ROWS,
       T.TOTAL_GOLD_ROWS - P.PREVIOUS_TOTAL_ROWS AS ADDED_ROWS,
       CASE
           WHEN P.PREVIOUS_TOTAL_ROWS IS NULL THEN 'FIRST_CHECK'
           WHEN T.TOTAL_GOLD_ROWS > P.PREVIOUS_TOTAL_ROWS THEN 'INCREASED'
           WHEN T.TOTAL_GOLD_ROWS = P.PREVIOUS_TOTAL_ROWS THEN 'UNCHANGED'
           ELSE 'DECREASED'
       END AS GROWTH_STATUS
FROM TOTALS T CROSS JOIN P;
