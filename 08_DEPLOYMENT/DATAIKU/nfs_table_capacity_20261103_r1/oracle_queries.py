"""Each statement is independently executable in a Dataiku AIDP SQL notebook."""
FILTER = "OWNER IN ('SIDDS','SIDDA') AND (TABLE_NAME LIKE 'LGL\\_%' ESCAPE '\\' OR TABLE_NAME LIKE 'LEGAL\\_%' ESCAPE '\\')"
TARGETS = 'targets AS (SELECT * FROM ALL_TABLES WHERE ' + FILTER + ')'
MAPPED = TARGETS + ''', regular AS (
SELECT t.* FROM targets t WHERE t.PARTITIONED='NO' AND t.IOT_TYPE IS NULL AND t.CLUSTER_NAME IS NULL
AND NOT EXISTS (SELECT 1 FROM ALL_INDEXES x WHERE x.TABLE_OWNER=t.OWNER AND x.TABLE_NAME=t.TABLE_NAME AND x.PARTITIONED='YES')),
mapped AS (
SELECT OWNER AS TABLE_OWNER,TABLE_NAME,OWNER AS SEGMENT_OWNER,TABLE_NAME AS SEGMENT_NAME FROM regular
UNION SELECT i.TABLE_OWNER,i.TABLE_NAME,i.OWNER,i.INDEX_NAME FROM ALL_INDEXES i JOIN regular t
ON i.TABLE_OWNER=t.OWNER AND i.TABLE_NAME=t.TABLE_NAME WHERE i.PARTITIONED='NO'
UNION SELECT l.OWNER,l.TABLE_NAME,l.OWNER,l.SEGMENT_NAME FROM ALL_LOBS l JOIN regular t
ON l.OWNER=t.OWNER AND l.TABLE_NAME=t.TABLE_NAME
UNION SELECT l.OWNER,l.TABLE_NAME,l.OWNER,l.INDEX_NAME FROM ALL_LOBS l JOIN regular t
ON l.OWNER=t.OWNER AND l.TABLE_NAME=t.TABLE_NAME)'''

SQL = {
 '01_IDENTITY': "SELECT SYS_CONTEXT('USERENV','SESSION_USER') AS LOGIN_USER, SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AS CURRENT_SCHEMA, SYS_CONTEXT('USERENV','DB_UNIQUE_NAME') AS DB_NAME, SYS_CONTEXT('USERENV','SERVICE_NAME') AS SERVICE_NAME FROM DUAL",
 '02_CHARACTER_SET': "SELECT PARAMETER,VALUE FROM NLS_DATABASE_PARAMETERS WHERE PARAMETER IN ('NLS_CHARACTERSET','NLS_NCHAR_CHARACTERSET') ORDER BY PARAMETER",
 '03_TABLES': 'WITH ' + TARGETS + ''' SELECT OWNER,TABLE_NAME,TABLESPACE_NAME,
NUM_ROWS AS STATS_ROWS,AVG_ROW_LEN,BLOCKS,LAST_ANALYZED,PARTITIONED,IOT_TYPE,CLUSTER_NAME,SEGMENT_CREATED,
CASE WHEN PARTITIONED='NO' AND IOT_TYPE IS NULL AND CLUSTER_NAME IS NULL
THEN 'NORMAL_HEAP' ELSE 'SPECIAL_LAYOUT_SIZE_NOT_COVERED' END AS LAYOUT_STATE
FROM targets ORDER BY OWNER,TABLE_NAME''',
 '04_INDEXES': 'WITH ' + TARGETS + ''' SELECT i.TABLE_OWNER,i.TABLE_NAME,i.OWNER AS INDEX_OWNER,i.INDEX_NAME,
i.INDEX_TYPE,i.UNIQUENESS,i.STATUS,i.PARTITIONED,i.TABLESPACE_NAME,i.NUM_ROWS AS STATS_ROWS,i.LAST_ANALYZED
FROM ALL_INDEXES i JOIN targets t ON i.TABLE_OWNER=t.OWNER AND i.TABLE_NAME=t.TABLE_NAME
ORDER BY i.TABLE_OWNER,i.TABLE_NAME,i.INDEX_NAME''',
 '05_LOB_SETTINGS': 'WITH ' + TARGETS + ''' SELECT l.OWNER,l.TABLE_NAME,l.COLUMN_NAME,l.SEGMENT_NAME,l.INDEX_NAME,
l.TABLESPACE_NAME,l.SECUREFILE,l.IN_ROW,l.CHUNK,l.COMPRESSION,l.DEDUPLICATION
FROM ALL_LOBS l JOIN targets t ON l.OWNER=t.OWNER AND l.TABLE_NAME=t.TABLE_NAME
ORDER BY l.OWNER,l.TABLE_NAME,l.COLUMN_NAME''',
 '06_ALLOCATED_DBA': 'WITH ' + MAPPED + ''', measured AS (
SELECT m.TABLE_OWNER,m.TABLE_NAME,SUM(s.BYTES) AS TOTAL_BYTES,
SUM(CASE WHEN s.SEGMENT_TYPE='TABLE' THEN s.BYTES ELSE 0 END) AS HEAP_BYTES,
SUM(CASE WHEN s.SEGMENT_TYPE='INDEX' THEN s.BYTES ELSE 0 END) AS INDEX_BYTES,
SUM(CASE WHEN s.SEGMENT_TYPE IN ('LOBSEGMENT','LOBINDEX') THEN s.BYTES ELSE 0 END) AS LOB_BYTES
FROM mapped m JOIN DBA_SEGMENTS s ON s.OWNER=m.SEGMENT_OWNER AND s.SEGMENT_NAME=m.SEGMENT_NAME
GROUP BY m.TABLE_OWNER,m.TABLE_NAME)
SELECT t.OWNER,t.TABLE_NAME,m.HEAP_BYTES,m.INDEX_BYTES,m.LOB_BYTES,
CASE WHEN t.PARTITIONED<>'NO' OR t.IOT_TYPE IS NOT NULL OR t.CLUSTER_NAME IS NOT NULL THEN NULL
WHEN t.SEGMENT_CREATED='NO' THEN 0 ELSE m.TOTAL_BYTES END AS TOTAL_BYTES,
CASE WHEN t.PARTITIONED<>'NO' OR t.IOT_TYPE IS NOT NULL OR t.CLUSTER_NAME IS NOT NULL THEN 'SPECIAL_LAYOUT_UNMEASURED'
WHEN t.SEGMENT_CREATED='NO' THEN 'NO_SEGMENT_CREATED'
WHEN m.TOTAL_BYTES IS NULL THEN 'UNMEASURED' ELSE 'MEASURED_ALLOCATION' END AS SIZE_STATE
FROM targets t LEFT JOIN measured m ON m.TABLE_OWNER=t.OWNER AND m.TABLE_NAME=t.TABLE_NAME
ORDER BY TOTAL_BYTES DESC NULLS LAST,t.OWNER,t.TABLE_NAME''',
 '07_ALLOCATED_OWN_SCHEMA': 'WITH ' + MAPPED + ''' SELECT m.TABLE_OWNER,m.TABLE_NAME,s.SEGMENT_TYPE,SUM(s.BYTES) AS ALLOCATED_BYTES
FROM mapped m JOIN USER_SEGMENTS s ON m.SEGMENT_OWNER=SYS_CONTEXT('USERENV','SESSION_USER') AND s.SEGMENT_NAME=m.SEGMENT_NAME
GROUP BY m.TABLE_OWNER,m.TABLE_NAME,s.SEGMENT_TYPE ORDER BY m.TABLE_OWNER,m.TABLE_NAME,s.SEGMENT_TYPE''',
 '08_QUOTA_DBA': "SELECT USERNAME,TABLESPACE_NAME,BYTES AS CHARGED_BYTES,MAX_BYTES AS QUOTA_BYTES FROM DBA_TS_QUOTAS WHERE USERNAME IN ('SIDDS','SIDDA') ORDER BY USERNAME,TABLESPACE_NAME",
 '09_SPACE_DBA': 'WITH ' + TARGETS + ''', names AS (
SELECT TABLESPACE_NAME FROM targets WHERE TABLESPACE_NAME IS NOT NULL
UNION SELECT i.TABLESPACE_NAME FROM ALL_INDEXES i JOIN targets t ON i.TABLE_OWNER=t.OWNER AND i.TABLE_NAME=t.TABLE_NAME WHERE i.TABLESPACE_NAME IS NOT NULL
UNION SELECT l.TABLESPACE_NAME FROM ALL_LOBS l JOIN targets t ON l.OWNER=t.OWNER AND l.TABLE_NAME=t.TABLE_NAME WHERE l.TABLESPACE_NAME IS NOT NULL),
d AS (SELECT TABLESPACE_NAME,SUM(BYTES) AS FILE_BYTES,
SUM(CASE WHEN AUTOEXTENSIBLE='YES' THEN GREATEST(MAXBYTES-BYTES,0) ELSE 0 END) AS AUTO_GROW_BYTES
FROM DBA_DATA_FILES GROUP BY TABLESPACE_NAME),
f AS (SELECT TABLESPACE_NAME,SUM(BYTES) AS FREE_BYTES,MAX(BYTES) AS MAX_FREE_EXTENT_BYTES FROM DBA_FREE_SPACE GROUP BY TABLESPACE_NAME)
SELECT n.TABLESPACE_NAME,d.FILE_BYTES,d.AUTO_GROW_BYTES,f.FREE_BYTES,f.MAX_FREE_EXTENT_BYTES
FROM names n LEFT JOIN d ON d.TABLESPACE_NAME=n.TABLESPACE_NAME LEFT JOIN f ON f.TABLESPACE_NAME=n.TABLESPACE_NAME
ORDER BY n.TABLESPACE_NAME''',
}


def run(query, output):
    import re
    from pathlib import Path
    from capacity import save_json, csv_write
    output=Path(output);output.mkdir(parents=True,exist_ok=False)
    result={}
    for name,sql in SQL.items():
        print('Oracle SELECT:',name,flush=True)
        try:
            rows=query(sql)
            result[name]=dict(status='OK',rows=rows)
            csv_write(output/(name+'.csv'),rows)
        except Exception as exc:
            result[name]=dict(status='UNAVAILABLE',error_type=type(exc).__name__,oracle_codes=sorted(set(re.findall(r'(?:ORA|PLS)-\d{5}',str(exc)))))
        save_json(output/'ORACLE_METADATA.json',result)
    print('Oracle 결과:',output)
    return result
