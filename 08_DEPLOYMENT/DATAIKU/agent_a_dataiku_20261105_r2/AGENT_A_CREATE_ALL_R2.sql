  UNION ALL SELECT 'LGL_EXEC_ST_A' T, 'SCOPE_HASH_VAL' C, 'VARCHAR2' DT, 64 DL, NULL DP, NULL DS, 'B' CU, 'N' NU FROM DUAL
  UNION ALL SELECT 'LGL_EXEC_ST_A' T, 'ST_KEY_ID' C, 'VARCHAR2' DT, 128 DL, NULL DP, NULL DS, 'B' CU, 'N' NU FROM DUAL
  UNION ALL SELECT 'LGL_EXEC_ST_A' T, 'CHG_SEQ_NO' C, 'NUMBER' DT, NULL DL, 18 DP, 0 DS, NULL CU, 'N' NU FROM DUAL
  UNION ALL SELECT 'LGL_EXEC_ST_A' T, 'ST_HASH_VAL' C, 'VARCHAR2' DT, 64 DL, NULL DP, NULL DS, 'B' CU, 'N' NU FROM DUAL
  UNION ALL SELECT 'LGL_EXEC_ST_A' T, 'ST_JSON_CN' C, 'CLOB' DT, NULL DL, NULL DP, NULL DS, NULL CU, 'N' NU FROM DUAL
), P AS (
  SELECT 'LGL_AGT_BODY_A' T, 'SCOPE_HASH_VAL,BODY_HASH_VAL,PART_SEQ_NO' PK_COLS FROM DUAL
  UNION ALL SELECT 'LGL_AGT_REC_A' T, 'SCOPE_HASH_VAL,OWNER_KEY_HASH_VAL,REC_KIND_CD,REC_KEY_HASH_VAL,REC_REV_NO' PK_COLS FROM DUAL
  UNION ALL SELECT 'LGL_AGT_RUN_A' T, 'SCOPE_HASH_VAL,RUN_KEY_HASH_VAL' PK_COLS FROM DUAL
  UNION ALL SELECT 'LGL_EXEC_ST_A' T, 'SCOPE_HASH_VAL,ST_KEY_ID' PK_COLS FROM DUAL
), A AS (
  SELECT TABLE_NAME T,COLUMN_NAME C,DATA_TYPE DT,DATA_LENGTH DL,DATA_PRECISION DP,DATA_SCALE DS,CHAR_USED CU,NULLABLE NU
  FROM ALL_TAB_COLUMNS WHERE OWNER='SIDDA' AND TABLE_NAME IN ('LGL_AGT_BODY_A','LGL_AGT_REC_A','LGL_AGT_RUN_A','LGL_EXEC_ST_A')
), ERRORS AS (
  SELECT COALESCE(E.T,A.T) T, COALESCE(E.C,A.C) C
  FROM E FULL OUTER JOIN A ON E.T=A.T AND E.C=A.C
  WHERE E.C IS NULL OR A.C IS NULL OR E.DT<>A.DT OR E.NU<>A.NU
     OR (E.DL IS NOT NULL AND NVL(A.DL,-1)<>E.DL)
     OR (E.DP IS NOT NULL AND NVL(A.DP,-1)<>E.DP)
     OR (E.DS IS NOT NULL AND NVL(A.DS,-1)<>E.DS)
     OR (E.CU IS NOT NULL AND NVL(A.CU,'?')<>E.CU)
), ACTUAL_PK AS (
  SELECT C.TABLE_NAME T, LISTAGG(K.COLUMN_NAME,',') WITHIN GROUP (ORDER BY K.POSITION) PK_COLS
  FROM ALL_CONSTRAINTS C JOIN ALL_CONS_COLUMNS K
    ON C.OWNER=K.OWNER AND C.CONSTRAINT_NAME=K.CONSTRAINT_NAME AND C.TABLE_NAME=K.TABLE_NAME
  WHERE C.OWNER='SIDDA' AND C.TABLE_NAME IN ('LGL_AGT_BODY_A','LGL_AGT_REC_A','LGL_AGT_RUN_A','LGL_EXEC_ST_A')
    AND C.CONSTRAINT_TYPE='P' AND C.STATUS='ENABLED' AND C.VALIDATED='VALIDATED'
  GROUP BY C.TABLE_NAME
)
SELECT P.T TABLE_NAME,
       CASE WHEN (SELECT COUNT(*) FROM ERRORS X WHERE X.T=P.T)=0 THEN 'PASS' ELSE 'FAIL' END COLUMNS_RESULT,
       CASE WHEN P.PK_COLS=K.PK_COLS THEN 'PASS' ELSE 'FAIL' END PK_RESULT,
       (SELECT COUNT(*) FROM A WHERE A.T=P.T) ACTUAL_COLUMNS,
       (SELECT LISTAGG(X.C,',') WITHIN GROUP (ORDER BY X.C) FROM ERRORS X WHERE X.T=P.T) MISMATCH_COLUMNS
FROM P LEFT JOIN ACTUAL_PK K ON P.T=K.T
ORDER BY P.T

