SELECT USER AS CONNECTION_USER, SYS_CONTEXT('USERENV','DB_NAME') AS DB_NAME,
       X.EXPECTED_TABLE, O.OWNER, O.OBJECT_TYPE, O.STATUS
FROM (SELECT 'LGL_AGT_BODY_A_1' AS EXPECTED_TABLE FROM DUAL
      UNION ALL SELECT 'LGL_AGT_REC_A_1' AS EXPECTED_TABLE FROM DUAL
      UNION ALL SELECT 'LGL_AGT_RUN_A_1' AS EXPECTED_TABLE FROM DUAL
      UNION ALL SELECT 'LGL_EXEC_ST_A_1' AS EXPECTED_TABLE FROM DUAL) X
LEFT JOIN ALL_OBJECTS O ON O.OWNER='SIDDA' AND O.OBJECT_NAME=X.EXPECTED_TABLE
ORDER BY X.EXPECTED_TABLE,O.OBJECT_TYPE
