-- 개발계 Dataiku Oracle 연결에서 이 SELECT 한 문장 전체를 실행합니다.
-- 기존 DEV_SILVER_ROW_COUNTS.sql 대신 이번 SQL을 사용합니다.
-- 대상: 현재 SIDDS.LGL_G19_*_S_1 테이블. SRCH_ROW와 구형 *_S는 제외합니다.
-- TOTAL_EXCL_SRCH_ROW는 아래 9개 테이블의 실제 행 수 합계입니다.
WITH COUNTS AS (
    SELECT 'LGL_G19_DOC_VER_S_1' AS TABLE_NAME, COUNT(*) AS ROW_COUNT
    FROM SIDDS.LGL_G19_DOC_VER_S_1
    UNION ALL
    SELECT 'LGL_G19_DOC_UNIT_S_1', COUNT(*)
    FROM SIDDS.LGL_G19_DOC_UNIT_S_1
    UNION ALL
    SELECT 'LGL_G19_DOC_BLK_S_1', COUNT(*)
    FROM SIDDS.LGL_G19_DOC_BLK_S_1
    UNION ALL
    SELECT 'LGL_G19_SRC_POST_S_1', COUNT(*)
    FROM SIDDS.LGL_G19_SRC_POST_S_1
    UNION ALL
    SELECT 'LGL_G19_SRCH_POST_S_1', COUNT(*)
    FROM SIDDS.LGL_G19_SRCH_POST_S_1
    UNION ALL
    SELECT 'LGL_G19_SRCH_CHNL_S_1', COUNT(*)
    FROM SIDDS.LGL_G19_SRCH_CHNL_S_1
    UNION ALL
    SELECT 'LGL_G19_VCTR_POST_S_1', COUNT(*)
    FROM SIDDS.LGL_G19_VCTR_POST_S_1
    UNION ALL
    SELECT 'LGL_G19_VCTR_ITEM_S_1', COUNT(*)
    FROM SIDDS.LGL_G19_VCTR_ITEM_S_1
    UNION ALL
    SELECT 'LGL_G19_VCTR_HEAD_S_1', COUNT(*)
    FROM SIDDS.LGL_G19_VCTR_HEAD_S_1
)
SELECT TABLE_NAME,
       ROW_COUNT,
       TO_CHAR(ROW_COUNT, 'FM999,999,999,999,990') AS ROW_COUNT_COMMA,
       SUM(ROW_COUNT) OVER () AS TOTAL_EXCL_SRCH_ROW
FROM COUNTS
ORDER BY ROW_COUNT DESC, TABLE_NAME;
