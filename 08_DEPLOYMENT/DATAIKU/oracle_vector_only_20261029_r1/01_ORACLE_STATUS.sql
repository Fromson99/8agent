-- Read only. Use the existing AIDP connection / SIDDS owner.
-- A completed Oracle publication is the source; no Dataiku 03 receipt is needed.
SELECT SRCH_PBLS_ID,
       JSON_VALUE(MNFST_JSON_CN,'$.status') AS STATUS,
       JSON_VALUE(MNFST_JSON_CN,'$.source_release_id') AS SOURCE_RELEASE_ID,
       JSON_VALUE(MNFST_JSON_CN,'$.dataset_version') AS DATASET_VERSION
  FROM SIDDS.LGL_SRCH_PBLS_S
 ORDER BY SRCH_PBLS_ID;

SELECT SRC_PBLS_ID, DATA_VER_ID,
       JSON_VALUE(PBLS_JSON_CN,'$.status') AS STATUS
  FROM SIDDS.LGL_SRC_PBLS_S ORDER BY SRC_PBLS_ID;

SELECT OWNER,TABLE_NAME,NUM_ROWS,LAST_ANALYZED
  FROM ALL_TABLES WHERE OWNER IN ('SIDDS','SIDDA')
   AND (TABLE_NAME LIKE 'LGL\_%' ESCAPE '\' OR TABLE_NAME LIKE 'LEGAL\_%' ESCAPE '\')
 ORDER BY OWNER,TABLE_NAME;
-- NUM_ROWS is statistics, not an exact live count or proof that a table is unused.

SELECT OWNER,NAME,TYPE,REFERENCED_OWNER,REFERENCED_NAME,REFERENCED_TYPE
  FROM ALL_DEPENDENCIES
 WHERE REFERENCED_OWNER IN ('SIDDS','SIDDA')
   AND (REFERENCED_NAME LIKE 'LGL\_%' ESCAPE '\' OR REFERENCED_NAME LIKE 'LEGAL\_%' ESCAPE '\')
 ORDER BY REFERENCED_OWNER,REFERENCED_NAME,OWNER,NAME;

SELECT c.OWNER,c.TABLE_NAME,c.CONSTRAINT_NAME,p.OWNER AS PARENT_OWNER,p.TABLE_NAME AS PARENT_TABLE
  FROM ALL_CONSTRAINTS c JOIN ALL_CONSTRAINTS p
    ON p.OWNER=c.R_OWNER AND p.CONSTRAINT_NAME=c.R_CONSTRAINT_NAME
 WHERE c.CONSTRAINT_TYPE='R' AND p.OWNER IN ('SIDDS','SIDDA')
 ORDER BY p.OWNER,p.TABLE_NAME,c.OWNER,c.TABLE_NAME;
-- Visibility depends on privileges. Dynamic SQL, external consumers and other DSS projects
-- are not fully covered by ALL_DEPENDENCIES. No DROP/TRUNCATE/DELETE is included.
