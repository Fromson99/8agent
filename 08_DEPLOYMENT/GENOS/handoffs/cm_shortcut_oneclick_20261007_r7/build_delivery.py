"""Seal one-click recipes on exact R4/R6 code, preserving known NFS list overlay."""
import ast
import base64
import contextlib
import gzip
import hashlib
import importlib.util
import io
import json
from pathlib import Path
import subprocess
import tempfile
import zipfile
import zlib

ROOT=Path(__file__).resolve().parents[4];OUT=Path(__file__).resolve().parent
R6=OUT.with_name('cm_shortcut_common_20261007_r6')
NFS=OUT.with_name('data_transfer_list_20261007_r1')
NAME='GENOS_CM_ONECLICK_20261007_R7'
HELPER='02_BACKEND/semantic_runtime/deployment_paths.py'
CONFIG='00_SYSTEM/GENOS_SERVING_PATHS.json'
sha=lambda v:hashlib.sha256(v).hexdigest()
encoded=lambda v:(json.dumps(v,ensure_ascii=False,indent=2)+'\n').encode()

def load(path,name):
    spec=importlib.util.spec_from_file_location(name,path);m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m);return m

def service_patch(raw):
    text=raw.decode();anchor='from semantic_runtime import observability as obs\n'
    assert text.count(anchor)==1
    lines='from semantic_runtime.deployment_paths import install as _install_deployment_paths, verify_generation as _verify_deployment_generation\n_DEPLOYMENT_PATHS = _install_deployment_paths(_ROOT)\n'
    log='_SYSTEM_LOGS = install_system_logging("service")\n'
    if log in text:text=text.replace(log,'',1);lines+=log
    text=text.replace(anchor,lines+anchor,1)
    anchor='    manifest = _json(generation / "manifest.json")\n'
    assert anchor in text
    text=text.replace(anchor,anchor+'    _verify_deployment_generation(_DEPLOYMENT_PATHS, generation)\n',1)
    ast.parse(text,feature_version=(3,11));return text.encode()

def main():
    assert not (OUT/(NAME+'_RUN.txt')).exists(),'sealed delivery requires a new revision'
    build=load(R6/'build_delivery.py','r6_build');lib=load(R6/'apply_cm.py','r6_library')
    r6spec=json.loads(gzip.decompress((R6/'PATCH_SPEC.json.gz').read_bytes()))
    nfs=load(NFS/'build_delivery.py','nfs_build')
    hook=load(ROOT/'06_TOOLS/COMMANDS/genos_nfs_probe_handoff.py','nfs_hook')
    with zipfile.ZipFile(NFS/'CODE_PAYLOAD.zip') as z:
        nfs_code={n:z.read(n) for n in z.namelist() if n!='CODE_MANIFEST.json'}
    package=(R6/'CM51_SOURCE_PACKAGE.json').read_bytes();helper=(ROOT/HELPER).read_bytes()
    spec={'revision':NAME,'r6_library':base64.b64encode((R6/'apply_cm.py').read_bytes()).decode(),
          'states':{},'recipes':{},'blobs':{},'package_sha256':sha(package),
          'paths':{'generation':'/nfs-root/diamo/8-agent/term-releases/financial-risk-success-20261005-schema-r2/generation',
                   'runtime':'/nfs-root/diamo/8-agent/runtime','state':None},
          'managed_paths':[HELPER,CONFIG,*nfs_code,*hook.HOOK_FILES]}
    spec['blobs'][sha(package)]=base64.b64encode(package).decode()
    test={'bases':[],'blobs':{}};results=[]
    for label,payload,_ in build.parent_states():
        with tempfile.TemporaryDirectory() as directory,contextlib.redirect_stdout(io.StringIO()):
            root=Path(directory);build.materialize(root,payload)
            current=json.loads(payload['CODE_MANIFEST.json'])
            if current.get('cm_curated_registration',{}).get('revision')==build.NAME:
                common=payload
            else:
                _,_,changes,_=lib.prepared(root,r6spec);common={**payload,**changes}
        candidates=[(label,payload,common)]
        candidates.append((label+'/cm-common-r6',common,common))
        for basis,original,common in candidates:
            for overlay in [True,False]:
                before={n:v for n,v in original.items() if n!='CODE_MANIFEST.json'}
                final={n:v for n,v in common.items() if n!='CODE_MANIFEST.json'}
                if overlay:
                    before.update(nfs_code);final.update(nfs_code)
                    for name,rootname in hook.HOOK_FILES.items():
                        before[name]=hook.hook(before[name],rootname);final[name]=hook.hook(final[name],rootname)
                final['service.py']=service_patch(final['service.py']);final[HELPER]=helper
                config=json.loads(final['00_SYSTEM/PIPELINE.json'])
                config['genos_operator_paths']={'config':CONFIG,'consumer':'service.py startup plus generation manifest verification',
                    'operator_setup':'generated by oneclick; no manual environment variables','local_without_config':'existing selection unchanged'}
                for entry in config['engines'].values():
                    name=entry['manifest'];engine=json.loads(final[name])
                    for path in engine['files']:
                        if path in final:engine['files'][path]=sha(final[path])
                    engine['files'][HELPER]=sha(helper)
                    final[name]=encoded(engine);entry['sha256']=sha(final[name])
                final['00_SYSTEM/PIPELINE.json']=encoded(config);lib.verify_bindings(final)
                name=basis+('/nfs-list-r1' if overlay else '')
                recipe={'label':name,'before':{n:sha(v) for n,v in before.items()},
                        'after':{n:sha(v) for n,v in final.items()},'patches':{}}
                for path,raw in final.items():
                    if before.get(path)==raw:continue
                    fingerprint=sha(raw);spec['blobs'][fingerprint]=base64.b64encode(raw).decode();recipe['patches'][path]=fingerprint
                recipe['id']=sha(encoded(recipe));spec['recipes'][recipe['id']]=recipe
                key=sha(original['CODE_MANIFEST.json']);spec['states'].setdefault(key,[]).append(recipe)
                results.append({'basis':name,'prior_inventory_sha256':key,'recipe_id':recipe['id'],'modified_static_files':sorted(recipe['patches'])})
                if '/original/' in basis and '/core-shortcut-r1' in basis and (basis.endswith('/cm-data-r4') and not overlay or basis.endswith('/cm-data-r4/cm-common-r6') and overlay):
                    b={**before,'CODE_MANIFEST.json':original['CODE_MANIFEST.json']}
                    for n,v in b.items():test['blobs'][sha(v)]=base64.b64encode(v).decode()
                    test['bases'].append({'label':name,'files':{n:sha(v) for n,v in b.items()},'recipe_id':recipe['id']})
    (OUT/'PATCH_SPEC.json.gz').write_bytes(gzip.compress(encoded(spec),mtime=0))
    (OUT/'TEST_BASES.json.gz').write_bytes(gzip.compress(encoded(test),mtime=0))
    code=(ROOT/'06_TOOLS/COMMANDS/genos_cm_oneclick.py').read_bytes();ast.parse(code,feature_version=(3,11))
    bundle=encoded({'code':base64.b64encode(code).decode(),'spec':spec})
    packed=base64.b64encode(zlib.compress(bundle,9)).decode()
    bootstrap=f'''import base64,hashlib,json,sys,types,zlib
raw=zlib.decompress(base64.b64decode({packed!r}))
assert hashlib.sha256(raw).hexdigest()=={sha(bundle)!r}
bundle=json.loads(raw);m=types.ModuleType('cm_oneclick')
exec(compile(base64.b64decode(bundle['code']),'genos_cm_oneclick.py','exec'),m.__dict__)
raise SystemExit(m.main(bundle['spec'],sys.argv[1:]))
'''
    script='''#!/usr/bin/env bash
set -Eeuo pipefail
umask 077
task_transfer="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
task_logs="$task_transfer/cm-oneclick-r7/logs"
mkdir -p -- "$task_logs"
task_log="$task_logs/$(date -u +%Y%m%dT%H%M%SZ)-$$.log"
exec > >(tee -a "$task_log") 2>&1
trap 'task_exit=$?; printf "EXIT=%s LOG=%s\\n" "$task_exit" "$task_log"' EXIT
printf '공통 CM 자동 적용 시작 LOG=%s\\n' "$task_log"
if [[ -x /venv/bin/python3 ]]; then task_python=/venv/bin/python3; else task_python=python3; fi
"$task_python" - "$task_transfer" "$@" <<'CM_ONECLICK_PY'
'''+bootstrap+'CM_ONECLICK_PY\n'
    run=OUT/(NAME+'_RUN.txt');run.write_text(script)
    subprocess.run(['bash','-n',str(run)],check=True)
    paths=json.loads((NFS/'HANDOFF.json').read_bytes())
    assert spec['paths']['generation']==paths['default_generation'] and spec['paths']['runtime']==paths['default_runtime'] and paths['default_state'] is None
    record={'version':NAME,'cases':51,'entries':98,'recipes':results,'input_inventories':len(spec['states']),
            'defaults':spec['paths'],'path_source_mail':'1a115df82c32b2f5','r6_source_binding_sha256':sha((R6/'SOURCE_BINDING.json').read_bytes()),
            'r6_source_package_sha256':sha(package),'oneclick_source_sha256':sha(code),'runtime_helper_sha256':sha(helper),
            'RUN_sha256':sha(run.read_bytes()),'serving_revision_deployment':'USER_UI_PENDING','field_verified':False,'model_calls':0}
    (OUT/'SOURCE_BINDING.json').write_bytes(encoded(record))
    print('BUILT',len(results),'sealed recipes;',len(spec['states']),'inventories;',len(test['bases']),'field test fixtures',flush=True)

if __name__=='__main__':main()
